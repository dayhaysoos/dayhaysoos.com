import React, { useEffect, useState } from "react";
import { Link } from "react-router-dom";

interface LogEntry {
  id: number;
  date: string;
  topic: string;
  content: string;
  tags: string[];
}

export default function BuilderLog() {
  const [logs, setLogs] = useState<LogEntry[]>([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    fetch("/api/logs")
      .then((res) => res.json())
      .then((data) => {
        setLogs(data);
        setLoading(false);
      })
      .catch((err) => {
        console.error("Failed to fetch logs:", err);
        setLoading(false);
      });
  }, []);

  return (
    <div className="min-h-screen bg-background text-foreground font-sans selection:bg-neutral-800 selection:text-white pb-20">
      <div className="max-w-2xl mx-auto px-6 pt-24">
        <header className="mb-16">
          <Link to="/" className="text-sm text-muted-foreground hover:text-foreground transition-colors mb-6 inline-block">
            ← Back home
          </Link>
          <h1 className="text-4xl font-bold tracking-tight mb-3">The Builder's Log</h1>
          <p className="text-muted-foreground text-lg">
            A real-time feed of engineering work, automated by Zo.
          </p>
        </header>

        {loading ? (
          <div className="text-center py-20 text-muted-foreground">Loading updates...</div>
        ) : (
          <div className="relative border-l border-border ml-3 space-y-12">
            {logs.map((entry) => (
              <div key={entry.id || entry.date} className="relative pl-10 group">
                {/* Timeline Dot */}
                <div className="absolute -left-[5px] top-2 w-2.5 h-2.5 rounded-full bg-border group-hover:bg-primary transition-colors duration-300" />
                
                <div className="flex flex-col sm:flex-row sm:items-baseline gap-2 mb-2">
                  <h3 className="text-xl font-semibold text-foreground group-hover:text-primary transition-colors">
                    {entry.topic}
                  </h3>
                  <span className="text-sm font-mono text-muted-foreground">
                    {entry.date}
                  </span>
                </div>
                
                <div className="bg-card rounded-xl p-6 border border-border/40 hover:border-border transition-colors shadow-sm">
                  <p className="text-card-foreground leading-relaxed mb-4 whitespace-pre-line">
                    {entry.content}
                  </p>
                  
                  {entry.tags && (
                    <div className="flex flex-wrap gap-2">
                      {entry.tags.map((tag, i) => (
                        <span key={i} className="text-xs font-medium px-2.5 py-1 rounded-md bg-secondary text-secondary-foreground border border-border/50">
                          {tag}
                        </span>
                      ))}
                    </div>
                  )}
                </div>
              </div>
            ))}
          </div>
        )}

        <div className="mt-20 pt-10 border-t border-border/40 text-center">
             <p className="text-sm text-muted-foreground">
                This log is automatically generated by <a href="https://zocomputer.com" className="hover:text-foreground underline decoration-muted-foreground/30 underline-offset-2">Zo</a> based on git activity.
             </p>
        </div>
      </div>
    </div>
  );
}


